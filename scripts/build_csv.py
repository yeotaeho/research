def clean(v):
    v = "" if v is None else str(v)
    return re.sub(r"\s+", " ", v).strip()


def load_reviews():
    rows, seen = [], set()
    for f in sorted(glob.glob(f"{WORK}/reviews_*.jsonl")):
        for line in open(f, encoding="utf-8"):
            if not line.strip():
                continue
            r = json.loads(line)
            r = {k: clean(r.get(k, "")) for k in REVIEW_COLS}
            if not r["source_url"].startswith("http"):
                continue
            key = (r["source_url"], r["item_summary"][:40])
            if key in seen:
                continue
            seen.add(key)
            rows.append(r)
    return rows


def write_csv(path, cols, rows):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, quoting=csv.QUOTE_ALL, lineterminator="\r\n")
        w.writeheader()
        for r in rows:
            w.writerow({c: clean(r.get(c, "")) for c in cols})


def main():
    stats_path = f"{ROOT}/modoo_yechang_stats.csv"
    reviews_path = f"{ROOT}/modoo_yechang_reviews.csv"
    write_csv(stats_path, STATS_COLS, STATS)
    reviews = load_reviews()
    write_csv(reviews_path, REVIEW_COLS, reviews)
    # 검증
    for path, cols in ((stats_path, STATS_COLS), (reviews_path, REVIEW_COLS)):
        with open(path, encoding="utf-8-sig", newline="") as f:
            rd = list(csv.DictReader(f))
        assert all(list(r.keys()) == cols for r in rd), path
        print(f"{os.path.basename(path)}: {len(rd)} rows")
        if "cohort" in cols:
            print("  program/cohort:", dict(Counter((r['program'], r['cohort']) for r in rd)))
            print("  stage:", dict(Counter(r['stage'] for r in rd)))
            assert all(r["source_url"].startswith("http") for r in rd)
        else:
            print("  program/year:", dict(Counter((r['program'], r['year']) for r in rd)))
            print("  stage:", dict(Counter(r['stage'] for r in rd)))
            print("  outcome:", dict(Counter(r['outcome'] for r in rd)))


if __name__ == "__main__":
    main()
